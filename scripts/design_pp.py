"""Design the push-pull power-amp clip curve (odd-symmetric, tube/NFB-shaped).

Real push-pull tube power amps with negative feedback:
  - odd-symmetric (even harmonics cancel in the OT)
  - soft cubic knee (x - x^3/3, the classic tube soft-clip) that shapes the
    whole wave -> strong h3, the "power-amp breakup" character
  - gradual saturating tail + ceiling, no flat-top square
This script verifies monotonicity/C1, measures the harmonic profile, and
prints C constants for core/ampsim.c.
"""
import numpy as np

FS = 44100.0

K1 = 1.0    # cubic soft-clip end
Y1 = 2.0 / 3.0
K2 = 2.30   # tail end
Y2 = 1.06   # tail ceiling
CEIL = 1.08

def curve(x):
    ax = abs(x)
    s = 1.0 if x >= 0.0 else -1.0
    if ax <= K1:
        y = ax - ax * ax * ax / 3.0
    elif ax <= K2:
        t = (ax - K1) / (K2 - K1)
        # cubic Hermite: y0=Y1 slope 0 -> y1=Y2 slope 0.05
        m1 = 0.05
        a = 2.0 * Y1 - 2.0 * Y2 + m1
        b = -3.0 * Y1 + 3.0 * Y2 - m1
        y = Y1 + b * t * t + a * t * t * t
    else:
        y = CEIL
    return s * y

# --- verify monotonic + C1 ---
xx = np.linspace(-5.0, 5.0, 500001)
yy = np.array([curve(v) for v in xx])
d = np.diff(yy)
if np.any(d < -1e-9):
    raise SystemExit("NOT monotonic!")
eps = 1e-4
for xj in (K1, K2):
    dl = (curve(xj + eps) - curve(xj - eps)) / (2 * eps)
    print(f"joint x={xj}: slope {dl:.4f}")

# --- THD measurement ---
def thd(drive):
    n = 16384
    cyc = 256
    w = 2.0 * np.pi * cyc / n
    x = drive * np.sin(w * np.arange(n))
    y = np.array([curve(v) for v in x])
    X = np.fft.rfft(y) / n * 2.0
    h = [abs(X[k * cyc]) for k in range(1, 11)]
    return h

print("\ndrive    h1      h3      h5      h7      h9      h11")
for drv in (0.5, 0.75, 1.0, 1.25, 1.5, 2.0, 3.0):
    h = thd(drv)
    row = [20 * np.log10(h[k - 1] + 1e-12) for k in (1, 3, 5, 7, 9, 11)]
    print(f"{drv:5.2f}  " + "  ".join(f"{v:6.1f}" for v in row[:6]))

# compression: output peak vs input peak
print("\ninput peak -> output peak (power-amp compression)")
for inp in (0.2, 0.35, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0):
    print(f"  {inp:4.2f} -> {curve(inp):.3f}")

# --- emit C code (positive half, N-1 segments + clamp) ---
print("\n/* generated by work/design_pp.py - push-pull odd clip, NFB-shaped */")
print("static float clip_pp(float x) {")
print("    float ax = x < 0.0f ? -x : x;")
print("    float s  = x < 0.0f ? -1.0f : 1.0f;")
print("    float y;")
print(f"    if (ax <= {K1:.2f}f) {{")
print("        y = ax - ax * ax * ax * 0.333333333f;")
print("    }")
m1 = 0.05
a3 = 2.0 * Y1 - 2.0 * Y2 + m1
b2 = -3.0 * Y1 + 3.0 * Y2 - m1
print(f"    else if (ax <= {K2:.2f}f) {{")
print(f"        float t = (ax - {K1:.2f}f) * {1.0 / (K2 - K1):.6f}f;")
print(f"        y = {Y1:.9f}f + t * t * ({b2:.9f}f + t * {a3:.9f}f);")
print("    }")
print(f"    else {{ y = {CEIL:.9f}f; }}")
print("    return s * y;")
print("}")
